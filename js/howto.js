// ---------------------------------------------------------------- 描く
const iconHTML = (t, cls = 'hp-ic') => `<img class="${cls}" src="${t.icon()}" alt="">`;

function partHTML(pt) {
  let h = `<section class="hp-part" ${pt.id ? `data-part="${pt.id}"` : ''}><h3>${pt.h}</h3>`;
  if (pt.p) h += `<p>${pt.p}</p>`;
  if (pt.steps) h += `<ol class="hp-steps">${pt.steps.map((s) => `<li>${s}</li>`).join('')}</ol>`;
  if (pt.rows) h += `<div class="hp-rows">${pt.rows.map(([src, k, v]) => `<div class="hp-row ${src ? 'has-ic' : ''}">${src ? `<img src="${src}" alt="">` : ''}<b>${k}</b><span>${v}</span></div>`).join('')}</div>`;
  if (pt.list) h += `<ul class="hp-list">${pt.list.map((s) => `<li>${s}</li>`).join('')}</ul>`;
  if (pt.html) h += pt.html;
  if (pt.note) h += `<p class="hp-note">${pt.note}</p>`;
  return h + '</section>';
}

// 1 つの項目の中身（見出し・ひとこと・各 part）
export function helpTopicHTML(id) {
  const t = helpTopics()[id];
  return `<div class="hp-topic">
    <div class="hp-head">${iconHTML(t)}<div><b>${t.jp}</b><small>${t.en}</small></div></div>
    <p class="hp-lead">${t.lead}</p>
    ${t.parts.map(partHTML).join('')}
  </div>`;
}

// 項目のカードを見出しごとに並べる。groups を省くと全部
export function helpIndexHTML(groups = HELP_GROUPS) {
  const T = helpTopics();
  return groups.map((g) => `<div class="hp-group"><div class="hp-gh"><span>${g.en}</span>${g.jp}</div>
    <div class="hp-tiles">${g.ids.map((id) => `<button class="hp-tile" data-topic="${id}">${iconHTML(T[id], 'hp-tic')}<span>${T[id].jp}</span></button>`).join('')}</div></div>`).join('');
}
